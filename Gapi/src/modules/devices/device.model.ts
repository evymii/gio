import { Schema, model } from 'mongoose';

export const PLATFORMS = ['ios', 'android', 'web'] as const;
export const LOCATION_PERMISSIONS = ['not_determined', 'denied', 'restricted', 'when_in_use', 'always'] as const;

/** devices — id, user_id, push_token, platform, location_permission. */
const deviceSchema = new Schema(
  {
    user: { type: Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    deviceId: { type: String, required: true }, // stable id generated by the app
    pushToken: { type: String, default: null }, // Firebase Cloud Messaging / APNs token
    platform: { type: String, enum: PLATFORMS, required: true },
    locationPermission: { type: String, enum: LOCATION_PERMISSIONS, default: 'not_determined' },
    appVersion: { type: String, default: null },
    lastSeenAt: { type: Date, default: () => new Date() },
  },
  { timestamps: true, collection: 'devices' },
);

deviceSchema.index({ user: 1, deviceId: 1 }, { unique: true });

export const Device = model('Device', deviceSchema);
